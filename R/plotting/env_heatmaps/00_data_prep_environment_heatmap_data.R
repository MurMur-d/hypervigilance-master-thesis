# 5) save_hv_matrix_table(): helper to write grid as CSV (optional I/O)
# ===================================================================================================

#' Save the hv matrix table as CSV so other scripts can re-use the same grid without rerunning.
#'
#' @param df data frame produced by the hypervigilance grid helpers
#' @param stem file path stem (without extension)
#' @return path to the written CSV (invisible)
#'
# Why this exists:
#   - Environment grids can be expensive to recompute.
#   - Saving the computed grid enables downstream scripts (or reviewers) to load the
#     exact data used for a figure without rerunning DP+simulation.
save_hv_matrix_table <- function(df, stem = file.path("outputs", "figures", "hv_matrix_over_env")) {
  if (!is.data.frame(df)) stop("df must be a data.frame")

  dir <- dirname(stem)
  if (!dir.exists(dir)) dir.create(dir, recursive = TRUE, showWarnings = FALSE)

  csv_path <- paste0(stem, ".csv")

  # Note: requires readr; ensure itâ€™s attached/imported somewhere in the project.
  readr::write_csv(df, csv_path)

  message("Saved HV matrix table: ", csv_path)
  invisible(csv_path)
}


