# File: prep_environment_heatmap_data.R
# Purpose:
#   Build the LA/LL hypervigilance grids AND the shared faceted heatmap builder used by
#   (almost) every downstream environment/mechanism figure.
#
# In plain language:
#   - We create a grid over environments, where each environment cell is defined by:
#       LA = stressor appearance probability/rate  (Î»A)
#       LL = stressor disappearance probability/rate (Î»L)
#   - For each cell we:
#       1) compute an optimal policy (DP) for a chosen model + cost parameters
#       2) simulate agents following that policy
#       3) compute hypervigilance statistics (including a canonical â€œsafe/no-stressorâ€ HV rate)
#   - We optionally repeat this for multiple K values (via K/D ratios) so we can facet by cost.
#   - We provide a plotting helper that standardizes:
#       axes, facet layout, labels, legend, and optional row-title layout used in paper panels
#
# Inputs:
#   - DP policy + simulation engines for basic and health models
#   - hv normalization/metadata helpers (prep_hypervigilance_data.R, hv_rate_helpers.R)
#   - model scenario definitions (utils_model_scenarios.R)
#   - shared plot layout helpers and subtitle utilities
#
# Outputs:
#   - Tables (data.frames) like hypervigilance_grid* that downstream scripts can reuse
#   - ggplot objects generated by plot_env_heatmap_faceted_by_K()
#
# Notes:
#   - Mostly pure transformations; minimal I/O (save_hv_matrix_table is the exception).
#   - Heavily annotated to make each aggregation decision reviewer-friendly.
# ===================================================================================================


