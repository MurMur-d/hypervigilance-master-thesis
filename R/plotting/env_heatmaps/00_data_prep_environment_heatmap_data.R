# 1) hypervigilance_grid(): compute one LAÃ—LL grid for a FIXED K
# ===================================================================================================

#' Build a tidy LA/LL grid for a fixed K cost.
#'
#' @param K vigilance cost
#' @param C baseline damage parameter (often â€œrelaxed baseline costâ€)
#' @param D damage parameter for vigilant agents (damage when stressor hits under vigilance)
#' @param d damage parameter for relaxed agents (damage when stressor hits under relaxation)
#' @param T_steps integer horizon length
#' @param states character vector of state labels (used by `mem_compute_policy` in basic model)
#' @param N_agents number of agents to simulate per LA/LL cell
#' @param grid_step numeric resolution for LA/LL axis
#' @param model character("basic","health")
#' @param policy_args list forwarded to `mem_compute_policy` (health model configuration, etc.)
#' @param sim_args list forwarded to `mem_simulate_agents` (health sim settings, etc.)
#' @return data.frame with hv statistics per grid cell
#'
#' @description
#'   For every (LA,LL) cell in a square grid:
#'     - compute optimal policy (cached)
#'     - simulate agents (cached)
#'     - compute HV rates and â€œprevent/spillâ€ metadata
#'
#' Parallelism:
#'   - Uses future.apply::future_lapply() so each grid cell can be evaluated concurrently.
hypervigilance_grid <- function(
    K, C, D, d,                 # cost/damage parameters
    T_steps,                    # time horizon
    states,                     # DP state labels for basic model (ignored by health implementation if unused)
    N_agents,                   # simulation sample size per cell
    grid_step = 0.1,            # LA/LL resolution (0..0.5)
    model = c("basic", "health"),
    policy_args = list(),
    sim_args    = list()
) {
  # Match and validate model identifier
  model <- match.arg(model)

  # Constraint check:
  # Many DP formulations in this project assume a parameter regime where vigilance
  # is not dominated by relaxation in all cases. The inequality:
  #   K + d <= C + D
  # appears to enforce that â€œvigilance cost + relaxed damageâ€ does not exceed
  # â€œbaseline cost + vigilant damageâ€ in a way that could break interpretation.
  # (Exactly why depends on the core model; this is a protective guardrail.)
  if ((K + d) > (C + D)) stop("Require K + d <= C + D.")

  # ---------------------------------------------------------------------------
  # Step 1: Expand the environment grid
  # ---------------------------------------------------------------------------
  # We evaluate LA and LL on a regular lattice.
  # Range is 0..0.5 by default because (in your project) LA/LL are typically
  # interpreted as probabilities per timestep bounded within this range.
  grid <- expand.grid(
    LA = seq(0, 0.5, by = grid_step),
    LL = seq(0, 0.5, by = grid_step),
    KEEP.OUT.ATTRS = FALSE
  )

  # ---------------------------------------------------------------------------
  # Step 2: Evaluate each grid cell (policy + simulation + HV metrics)
  # ---------------------------------------------------------------------------
  # We parallelize over rows of `grid`.
  #
  # future.seed = TRUE:
  #   - ensures reproducible randomness across workers
  #   - crucial because results should not depend on scheduling / worker count
  #
  # future.packages:
  #   - packages that must be available on worker sessions
  #   - mem_* functions and sourced helpers must already be visible in worker env
  rows <- future.apply::future_lapply(
    seq_len(nrow(grid)),
    future.seed = TRUE,
    future.packages = c("dplyr"),
    FUN = function(i) {

      # Pull LA/LL for this cell
      LAi <- grid$LA[i]
      LLi <- grid$LL[i]

      # --- 2A: Compute optimal policy (cached) --------------------------------
      # mem_compute_policy() is expected to:
      #   - use on-disk caching keyed by model+params+policy_args
      #   - return a policy data.frame
      pol <- mem_compute_policy(
        model = model,
        K = K, C = C, D = D, d = d,
        LA = LAi, LL = LLi,
        T_steps = T_steps,
        states = states,
        policy_args = policy_args
      )

      # --- 2B: Simulate agents forward (cached) -------------------------------
      # mem_simulate_agents() is expected to:
      #   - accept policy_df + env params + sim args
      #   - return list(sim$agent_data, sim$agent_stats, ...)
      # The agent_data must contain (possibly normalized later):
      #   time, agent, action, hv, stressor indicator, etc.
      sim <- mem_simulate_agents(
        model = model,
        policy_df = pol,
        LA = LAi, LL = LLi,
        T_steps = T_steps,
        N_agents = N_agents,
        K = K, C = C, D = D, d = d,
        sim_args = sim_args
      )

      # Extract agent-level panel data
      ad <- sim$agent_data

      # --- 2C: Compute canonical HV rates + metadata --------------------------
      # compute_hv_rates_from_agent_data() returns a rich list:
      #   HypervigilanceRate_all
      #   HypervigilanceRate_filtered (canonical: pooled mean on no-stressor rows)
      #   Spread_no_stressor (variability on no-stressor rows)
      #   coverage diagnostics and hv_meta payload
      hv_rates <- compute_hv_rates_from_agent_data(ad, T_steps = T_steps, N_agents = N_agents)

      # hv_meta comes from extract_hypervigilance_metadata() under the hood and
      # may contain breakdowns like:
      #   safe_hv: hv during safe/no-stressor windows
      #   prevent/spill counts: decomposition into preventive vs spillover HV
      hv_meta <- hv_rates$hv_meta

      # For readability
      hv_filtered <- hv_rates$HypervigilanceRate_filtered  # canonical safe-pooled mean
      hv_all      <- hv_rates$HypervigilanceRate_all       # pooled mean over all rows

      # --- 2D: Return one-row summary for this grid cell ----------------------
      # We build a plain data.frame for compatibility and speed in bind_rows().
      data.frame(
        LA = LAi,
        LL = LLi,
        K  = K,
        D  = D,

        # autocorr proxy:
        # In a simple two-state stressor Markov process, a common rough proxy
        # for persistence/autocorrelation is 1 - (LA + LL). We clamp to [0,1]
        # because rates outside that range can occur at edges or unusual inputs.
        autocorr = pmin(pmax(1 - (LAi + LLi), 0), 1),

        # HV metrics used by downstream plots
        HypervigilanceRate_all       = hv_all,
        HypervigilanceRate_filtered  = hv_filtered,

        # Additional hv_meta signals (coalesce missing to 0 for robustness)
        HypervigilanceSafeHV         = dplyr::coalesce(hv_meta$safe_hv, 0),
        HypervigilancePreventCount   = dplyr::coalesce(hv_meta$prevent, 0),
        HypervigilanceSpillCount     = dplyr::coalesce(hv_meta$spill, 0),

        # Diagnostics
        Spread_no_stressor           = hv_rates$Spread_no_stressor,
        Prop_timesteps_included      = dplyr::coalesce(hv_rates$Prop_timesteps_included, 0),
        Prop_agent_timesteps         = dplyr::coalesce(hv_rates$Prop_agent_timesteps, 0),

        stringsAsFactors = FALSE
      )
    }
  )

  # Bind per-cell rows into one large grid table
  dplyr::bind_rows(rows)
}


