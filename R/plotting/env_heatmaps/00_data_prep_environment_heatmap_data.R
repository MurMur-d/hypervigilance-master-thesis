# 3) hypervigilance_grid_by_Kratio_by_model(): stack grids across model scenarios
# ===================================================================================================

#' Stack env grids across predefined model scenarios.
#'
#' @param model_scenarios list of named scenarios (label + policy/sim args)
#' @param D,C,d,T_steps,states,N_agents same as other grid functions
#' @param grid_step numeric LA/LL resolution
#' @param ratio_step numeric ratio step for K/D
#' @param base_policy_args list merged with scenario-specific policy args
#' @param base_sim_args list merged with scenario-specific sim args
#' @return data.frame stacked across scenario labels for faceted plotting
#'
#' @details
#'   Many figures compare multiple â€œmodel variantsâ€ (e.g., basic vs health,
#   health with/without terminal reward). Each scenario defines:
#     - a model family ("basic" or "health")
#     - policy_args and sim_args overrides
#     - a display label for row facets
#   This function:
#     - runs hypervigilance_grid_by_Kratio() per scenario
#     - adds model_label/model_id/model columns so plotting can facet by rows
#     - stores row order as an attribute for consistent panel layout
hypervigilance_grid_by_Kratio_by_model <- function(
    model_scenarios = default_env_model_scenarios,
    D, C, d, T_steps, states, N_agents,
    grid_step = 0.1,
    ratio_step = 0.2,
    base_policy_args = list(),
    base_sim_args = list()
) {
  if (length(model_scenarios) == 0) stop("model_scenarios must have at least one entry")

  # Determine row facet order (labels) in advance so it stays stable.
  row_levels <- vapply(seq_along(model_scenarios), function(i) {
    lbl <- model_scenarios[[i]]$label
    if (is.null(lbl) || !nzchar(lbl)) paste0("model ", i) else lbl
  }, character(1))

  # Run each scenario and tag it for faceting
  rows <- lapply(seq_along(model_scenarios), function(i) {
    scenario <- model_scenarios[[i]]

    # Default to health if not specified (project convention)
    model <- if (is.null(scenario$model)) "health" else scenario$model

    # Merge base args with scenario overrides.
    # This ensures global settings (like h0) can be supplied once and
    # scenario differences can be minimal.
    pol_args <- merge_model_args(base_policy_args, scenario$policy_args)
    sim_args <- merge_model_args(base_sim_args, scenario$sim_args)

    # Compute scenario grid (may be large; relies on caching + parallelism)
    df <- hypervigilance_grid_by_Kratio(
      D = D, C = C, d = d,
      T_steps = T_steps, states = states, N_agents = N_agents,
      grid_step = grid_step, ratio_step = ratio_step,
      model = model, policy_args = pol_args, sim_args = sim_args
    )
    if (nrow(df) == 0) return(NULL)

    # Add facet identifiers used downstream:
    df$model_label <- row_levels[i]  # human-facing label
    df$model_id    <- i              # numeric id (stable order)
    df$model       <- model          # "basic" or "health"
    df
  })

  # Drop scenarios that produced no rows (e.g., invalid param regimes)
  rows <- Filter(Negate(is.null), rows)
  if (length(rows) == 0) return(data.frame())

  # Stack all scenarios
  out <- dplyr::bind_rows(rows)

  # Ensure model_label is a factor with the intended row order
  out$model_label <- factor(out$model_label, levels = row_levels[row_levels %in% out$model_label])

  # Store row order in an attribute so plotting wrappers can reuse it
  attr(out, "row_levels") <- levels(out$model_label)

  out
}


