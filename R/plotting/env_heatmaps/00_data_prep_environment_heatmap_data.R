# 2) hypervigilance_grid_by_Kratio(): augment LAÃ—LL grid with a sweep over K/D ratio
# ===================================================================================================

#' Sweep K/D ratios across the LA/LL grid to build an augmented dataset.
#'
#' @param D base damage parameter
#' @param C baseline damage parameter
#' @param d relaxed damage
#' @param T_steps integer horizon
#' @param states character vector of DP states
#' @param N_agents number of simulated agents
#' @param grid_step resolution for LA/LL grid
#' @param ratio_step step size for D*K ratio
#' @param model character("basic","health")
#' @param policy_args list forwarded to `mem_compute_policy`
#' @param sim_args list forwarded to `mem_simulate_agents`
#' @return data.frame with hv rates + K ratio metadata
#'
#' @details
#'   This function exists because many environment heatmap figures are faceted by
#'   vigilance cost K. Rather than recomputing separate grids per K manually,
#'   we create a single long dataset with an explicit RatioDK and K column.
#'
#'   RatioDK is used as an â€œinterpretable sweep axisâ€:
#'     K = round(D * RatioDK)
#'   so the cost scale remains comparable across different D settings.
hypervigilance_grid_by_Kratio <- function(
    D, C, d, T_steps, states, N_agents,
    grid_step = 0.1,
    ratio_step = 0.2,
    model = c("basic", "health"),
    policy_args = list(),
    sim_args    = list()
) {
  model <- match.arg(model)

  # ---------------------------------------------------------------------------
  # Step 1: Build augmented grid LA Ã— LL Ã— RatioDK
  # ---------------------------------------------------------------------------
  # RatioDK ranges 0.1..0.9 by default; you can adjust depending on paper design.
  grid <- expand.grid(
    LA      = seq(0, 0.5, by = grid_step),
    LL      = seq(0, 0.5, by = grid_step),
    RatioDK = seq(0.1, 0.9, by = ratio_step),
    KEEP.OUT.ATTRS = FALSE
  ) |>
    # Convert ratio into an integer-ish K so faceting uses stable discrete values.
    dplyr::mutate(K = as.integer(round(D * RatioDK))) |>
    # Enforce same feasibility constraint as before:
    # (drop combinations where K is too large relative to costs/damages)
    dplyr::filter((K + d) <= (C + D))

  # If everything was filtered out (e.g., extreme params), return an empty df
  if (nrow(grid) == 0) return(grid[0, ])

  # ---------------------------------------------------------------------------
  # Step 2: Evaluate each augmented cell (parallel)
  # ---------------------------------------------------------------------------
  rows <- future.apply::future_lapply(
    seq_len(nrow(grid)),
    future.seed = TRUE,
    future.packages = c("dplyr"),
    FUN = function(i) {

      # Parameters for this cell
      LAi <- grid$LA[i]
      LLi <- grid$LL[i]
      Ki  <- grid$K[i]

      # --- 2A: Policy (cached) ------------------------------------------------
      pol <- mem_compute_policy(
        model = model,
        K = Ki, C = C, D = D, d = d,
        LA = LAi, LL = LLi,
        T_steps = T_steps,
        states = states,
        policy_args = policy_args
      )

      # --- 2B: Simulation (cached) -------------------------------------------
      sim <- mem_simulate_agents(
        model = model,
        policy_df = pol,
        LA = LAi, LL = LLi,
        T_steps = T_steps,
        N_agents = N_agents,
        K = Ki, C = C, D = D, d = d,
        sim_args = sim_args
      )

      # Some older codepaths compute hv_rate per-agent in sim$agent_stats.
      # We keep this as an optional extra metric when it exists, but we prefer
      # canonical pooled safe/no-stressor HV from hv_rate_helpers.
      stats <- sim$agent_stats
      ad    <- sim$agent_data

      hv_rates <- compute_hv_rates_from_agent_data(ad, T_steps = T_steps, N_agents = N_agents)
      hv_meta  <- hv_rates$hv_meta
      hv_filtered <- hv_rates$HypervigilanceRate_filtered
      hv_all      <- hv_rates$HypervigilanceRate_all

      # Optional: â€œagent mean hv_rateâ€ if agent_stats has hv_rate column
      hv_rate_stat <- if ("hv_rate" %in% names(stats)) {
        dplyr::coalesce(mean(stats$hv_rate, na.rm = TRUE), NA_real_)
      } else {
        NA_real_
      }

      # One-row summary
      data.frame(
        LA = LAi,
        LL = LLi,
        K  = Ki,
        D  = D,
        RatioDK = grid$RatioDK[i],

        autocorr = pmin(pmax(1 - (LAi + LLi), 0), 1),

        HypervigilanceRate_all       = hv_all,
        HypervigilanceRate_filtered  = hv_filtered,

        # Safe-window HV counts and decomposition (if provided by hv_meta)
        HypervigilanceSafeHV         = dplyr::coalesce(hv_meta$safe_hv, 0),
        HypervigilanceSafeSteps      = dplyr::coalesce(hv_meta$safe_steps, 0),
        HypervigilancePreventCount   = dplyr::coalesce(hv_meta$prevent, 0),
        HypervigilanceSpillCount     = dplyr::coalesce(hv_meta$spill, 0),

        # Optional legacy-style per-agent summary
        HypervigilanceRate_agent_mean = hv_rate_stat,

        # Diagnostics
        Spread_no_stressor           = hv_rates$Spread_no_stressor,
        Prop_timesteps_included      = dplyr::coalesce(hv_rates$Prop_timesteps_included, 0),
        Prop_agent_timesteps         = dplyr::coalesce(hv_rates$Prop_agent_timesteps, 0),

        stringsAsFactors = FALSE
      )
    }
  )

  dplyr::bind_rows(rows)
}


