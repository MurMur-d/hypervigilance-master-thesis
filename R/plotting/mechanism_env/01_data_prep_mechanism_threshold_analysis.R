# Column-detection and grid-navigation helpers
# =============================================================================

# Detect which column identifies the model.
# Some pipelines use `model_label`, others use `model`.
detect_model_column <- function(df) {
  for (candidate in c("model_label", "model")) {
    if (candidate %in% names(df)) return(candidate)
  }
  stop("Could not detect a model column; expected 'model_label' or 'model'.")
}

# Pick a default slice value when none is supplied.
# Preference order:
#   - Explicitly meaningful values (e.g., 0.2, 0.3)
#   - Otherwise, the midpoint of the available grid
pick_default_slice <- function(values, prefer = c(0.2, 0.3)) {
  uniq_vals <- sort(unique(values))
  if (length(uniq_vals) == 0) return(NA_real_)
  preferred <- intersect(prefer, uniq_vals)
  if (length(preferred) > 0) return(preferred[[1]])
  uniq_vals[ceiling(length(uniq_vals) / 2)]
}

# Find the largest grid value <= target
calc_floor <- function(target, grid) {
  if (is.na(target)) return(NA_real_)
  grid <- sort(unique(grid[!is.na(grid)]))
  if (length(grid) == 0 || target < min(grid)) return(NA_real_)
  candidates <- grid[grid <= target]
  if (length(candidates) == 0) return(NA_real_)
  max(candidates)
}

# Find the smallest grid value >= target
calc_ceil <- function(target, grid) {
  if (is.na(target)) return(NA_real_)
  grid <- sort(unique(grid[!is.na(grid)]))
  if (length(grid) == 0 || target > max(grid)) return(NA_real_)
  candidates <- grid[grid >= target]
  if (length(candidates) == 0) return(NA_real_)
  min(candidates)
}

# Safely pull a value from a data frame that might be empty
safe_pull <- function(data, column) {
  if (nrow(data) == 0) return(NA_real_)
  data[[column]][1]
}


# =============================================================================
# Vertical threshold analysis: crossing λA*
# =============================================================================
# Question answered:
#   Holding λL fixed, how does hypervigilance change as λA crosses λA* = K / D ?
#
# Interpretation:
#   This corresponds to the *preventative vigilance threshold* in safe states.
# =============================================================================

vertical_threshold_summary <- function(
    df,
    lambda_l_slice = NULL,
    rate_column = "HypervigilanceRate_all"
) {
  df <- tibble::as_tibble(df)
  model_col <- detect_model_column(df)

  if (!(rate_column %in% names(df))) {
    stop(sprintf("Column '%s' is missing from the supplied data frame.", rate_column))
  }

  # Choose which λL slice to examine
  ll_values <- sort(unique(df$LL))
  if (length(ll_values) == 0) return(tibble())

  slice_value <- lambda_l_slice %||% pick_default_slice(ll_values)
  if (!slice_value %in% ll_values) {
    stop(sprintf("lambda_l_slice must be one of: %s", paste(ll_values, collapse = ", ")))
  }

  # Restrict to that horizontal slice
  df_slice <- df %>% filter(LL == slice_value)
  la_grid <- sort(unique(df_slice$LA))
  if (length(la_grid) == 0) return(tibble())

  rate_sym <- rlang::sym(rate_column)

  # For each model × cost, compute analytic λA*
  combos <- df_slice %>%
    transmute(
      model = as.character(.data[[model_col]]),
      vigilance_cost = K,
      D
    ) %>%
    distinct() %>%
    arrange(model, vigilance_cost) %>%
    mutate(
      lambda_a_star  = vigilance_cost / D,
      lambda_a_below = purrr::map_dbl(lambda_a_star, calc_floor, grid = la_grid),
      lambda_a_above = purrr::map_dbl(lambda_a_star, calc_ceil,  grid = la_grid)
    )

  # Lookup table: hv at each grid LA
  hv_lookup <- df_slice %>%
    transmute(
      model = as.character(.data[[model_col]]),
      vigilance_cost = K,
      LA,
      hv_value = !!rate_sym
    )

  hv_below <- hv_lookup %>% rename(lambda_a_below = LA, hv_below = hv_value)
  hv_above <- hv_lookup %>% rename(lambda_a_above = LA, hv_above = hv_value)

  combos %>%
    left_join(hv_below, by = c("model", "vigilance_cost", "lambda_a_below")) %>%
    left_join(hv_above, by = c("model", "vigilance_cost", "lambda_a_above")) %>%
    mutate(
      delta_hv = if_else(
        is.na(hv_below) | is.na(hv_above),
        NA_real_,
        hv_above - hv_below
      ),
      lambda_l_slice = slice_value
    ) %>%
    select(
      model, vigilance_cost, lambda_l_slice,
      lambda_a_star,
      lambda_a_below, hv_below,
      lambda_a_above, hv_above,
      delta_hv
    )
}


# =============================================================================
# Horizontal threshold analysis: crossing λL*
# =============================================================================
# Question answered:
