# =============================================================================
# Diagonal threshold analysis: crossing πS = K / D
# =============================================================================
# Question answered:
#   How does hypervigilance change when the *overall stress probability*
#   πS = LA / (LA + LL) crosses the analytic indifference boundary?
#
# Interpretation:
#   This captures the *time-averaged vigilance threshold* across environments.
# =============================================================================

diagonal_threshold_summary <- function(
    df,
    rate_column = "HypervigilanceRate_all"
) {
  df <- tibble::as_tibble(df)
  model_col <- detect_model_column(df)

  if (!(rate_column %in% names(df))) {
    stop(sprintf("Column '%s' is missing from the supplied data frame.", rate_column))
  }

  df <- df %>%
    mutate(pi_S = if_else((LA + LL) <= 0, NA_real_, LA / (LA + LL)))

  combos <- df %>%
    transmute(
      model = as.character(.data[[model_col]]),
      vigilance_cost = K,
      D,
      target_pi_S = K / D
    ) %>%
    distinct() %>%
    arrange(model, vigilance_cost)

  if (nrow(combos) == 0) return(tibble())

  summaries <- purrr::map_dfr(seq_len(nrow(combos)), function(i) {
    row <- combos[i, ]

    subset <- df %>%
      filter(
        .data[[model_col]] == row$model,
        K == row$vigilance_cost,
        !is.na(pi_S)
      )

    below <- subset %>%
      filter(pi_S <= row$target_pi_S) %>%
      arrange(desc(pi_S)) %>%
      slice_head(n = 1)

    above <- subset %>%
      filter(pi_S >= row$target_pi_S) %>%
      arrange(pi_S) %>%
      slice_head(n = 1)

    tibble(
      model = row$model,
      vigilance_cost = row$vigilance_cost,
      target_pi_S = row$target_pi_S,

      lambda_a_below = safe_pull(below, "LA"),
      lambda_l_below = safe_pull(below, "LL"),
      pi_s_below = safe_pull(below, "pi_S"),
      hv_below = safe_pull(below, rate_column),

      lambda_a_above = safe_pull(above, "LA"),
      lambda_l_above = safe_pull(above, "LL"),
      pi_s_above = safe_pull(above, "pi_S"),
      hv_above = safe_pull(above, rate_column)
    )
  })

  summaries %>%
    mutate(
      delta_hv = if_else(
        is.na(hv_below) | is.na(hv_above),
        NA_real_,
        hv_above - hv_below
      )
    )
}


# =============================================================================
# Master entry point
# =============================================================================
# Runs the full threshold analysis using project defaults and returns
# all three summaries as a named list.
# =============================================================================

run_threshold_analysis <- function() {
  states   <- c("K", "Kd", "C", "CD")
  T_steps <- 10
  N_agents <- validate_default("N")
  C <- 0
  D <- validate_default("D")
  d <- validate_default("d")

  hv_env_models <- hypervigilance_grid_by_Kratio_by_model(
    model_scenarios = default_env_model_scenarios,
    D = D, C = C, d = d,
    T_steps = T_steps,
    states = states,
    N_agents = N_agents,
    grid_step = 0.1,
    ratio_step = 0.2
  )

  invisible(list(
    vertical   = vertical_threshold_summary(hv_env_models),
    horizontal = horizontal_threshold_summary(hv_env_models),
    diagonal   = diagonal_threshold_summary(hv_env_models)
  ))
}

