# ============================================================
# File: prep_mechanism_threshold_analysis.R
#
# Purpose:
#   Construct table-ready summaries that compare *analytic vigilance thresholds*
#   against *empirical hypervigilance values* measured on discretized LA/LL grids.
#
#   These helpers power Fig 4E and related tables by answering:
#     - What happens to hypervigilance just below vs just above λA* ?
#     - What happens just below vs just above λL* ?
#     - What happens when crossing the diagonal πS = K / D boundary?
#
# Key idea:
#   Analytic thresholds (λA*, λL*, πS*) rarely fall *exactly* on the discretized grid.
#   Therefore, we:
#     1) Compute the analytic threshold
#     2) Identify the nearest grid points just below and just above it
#     3) Compare hypervigilance rates across that crossing
#
# Notes:
#   - NO simulations occur here.
#   - This module strictly *post-processes* the grid generated by
#     `hypervigilance_grid_by_Kratio_by_model()`.
#   - All summaries are robust to missing grid points.
# ============================================================

